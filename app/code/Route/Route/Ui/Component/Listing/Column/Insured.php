namespace Route\Route\Ui\Component\Listing\Column;

use Magento\Ui\Component\Listing\Columns\Column;
use Route\Route\Helper\Data;

/**
 * Class that handle value from Route Column
 *
 * Php version 7.0^
 *
 * @category
 * @package   Route_Route
 * @author    Route Development Team <dev@routeapp.io>
 * @copyright 2019 Route App Inc. Copyright (c) https://www.routeapp.io/
 * @license   https://www.routeapp.io/merchant-terms-of-use  Proprietary License
 * @link      https://magento.routeapp.io/magento2/index.html
 */
class Insured extends Column
{

    /**
     * Prepare data before render it
     *
     * @param array $dataSource
     *
     * @return array
     */
    public function prepareDataSource(array $dataSource)
    {
        $dataSource = parent::prepareDataSource($dataSource);

        if (empty($dataSource['data']['items'])) {
            return $dataSource;
        }

        $fieldName = $this->getData('name');

        foreach ($dataSource['data']['items'] as &$item) {
            if (isset($item[Data::ROUTE_IS_INSURED])) {
                $item[$fieldName] = $item[Data::ROUTE_IS_INSURED] > 0 ? "Yes" : "No";
            }
        }

        return $dataSource;
    }
}
